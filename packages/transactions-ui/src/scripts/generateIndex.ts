/**
 * Generates src/index.ts, the package's only public entry, from the view modules.
 *
 *   bun transactions-ui generate:index           # write src/index.ts
 *   bun transactions-ui generate:index --check   # exit 1 when src/index.ts is stale
 *
 * Every export of every module under src/<area>/ is re-exported, except test, story and
 * platform-leg files (the base file carries the contract) and declarations marked
 * `@internal`. Names must be unique across the package: one name, one component, so a
 * search finds the one that exists.
 *
 * Nx's `prepare` target runs this before typecheck, lint and test. It writes the file
 * locally and only checks it when CI is set, so a stale committed index still fails CI
 * (here and in generateIndex.test.ts) instead of being regenerated over.
 *
 * Deliberately dependency-free (regex over declarations, like the ledger): views export
 * at the declaration, so `export { x }`, `export type { x }`, `export *` and default
 * exports are rejected instead of parsed.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

export const PACKAGE_NAME = '@universe/transactions-ui'
const PRINT_WIDTH = 120

const SKIPPED_DIRS = new Set(['scripts'])
const SKIPPED_FILE = /\.(test|stories|native|web|ios|android)\.tsx?$|\.d\.ts$/

const HEADER = `// oxlint-disable-next-line typescript/triple-slash-reference
/// <reference path="../../../index.d.ts" />

// @universe/transactions-ui: presentational transaction views. All data via props, actions
// via callbacks, zero imports from business logic or analytics code. Rules: CLAUDE.md.
// Generated by src/scripts/generateIndex.ts. Do not edit; run \`bun transactions-ui generate:index\`.
`

const DECLARATION =
  /^export\s+(?:declare\s+)?(?:async\s+)?(function\*?|const|let|class|abstract\s+class|enum|interface|type)\s+([A-Za-z_$][\w$]*)/
const UNSUPPORTED = /^export\s+(?:type\s+)?(?:\{|\*)|^export\s+default\b/

interface ExportedName {
  name: string
  typeOnly: boolean
}

interface ModuleExports {
  /** Module specifier, e.g. `@universe/transactions-ui/src/swap/Rate/RateRow`. */
  specifier: string
  names: ExportedName[]
}

function listModules(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((entry) => {
      const path = join(dir, entry)
      if (statSync(path).isDirectory()) {
        return SKIPPED_DIRS.has(entry) ? [] : listModules(path)
      }
      return /\.tsx?$/.test(entry) && !SKIPPED_FILE.test(entry) ? [path] : []
    })
}

/** True when the declaration starting at `lineIndex` sits under a JSDoc block tagged `@internal`. */
function isInternal(lines: string[], lineIndex: number): boolean {
  let i = lineIndex - 1
  if (i < 0 || !lines[i]?.trim().endsWith('*/')) {
    return false
  }
  for (; i >= 0; i--) {
    const line = lines[i] ?? ''
    if (line.includes('@internal')) {
      return true
    }
    if (line.trim().startsWith('/**')) {
      return false
    }
  }
  return false
}

function parseExports(path: string, source: string): ExportedName[] {
  const lines = source.split('\n')
  const names: ExportedName[] = []
  lines.forEach((line, index) => {
    if (UNSUPPORTED.test(line)) {
      throw new Error(`${path}:${index + 1}: export at the declaration; re-exports and default exports are not indexed`)
    }
    const match = DECLARATION.exec(line)
    if (!match?.[1] || !match[2] || isInternal(lines, index)) {
      return
    }
    names.push({ name: match[2], typeOnly: match[1] === 'interface' || match[1] === 'type' })
  })
  return names
}

export function collectExports(srcDir: string): ModuleExports[] {
  const modules: ModuleExports[] = []
  const owners = new Map<string, string>()

  for (const area of readdirSync(srcDir).sort()) {
    const areaDir = join(srcDir, area)
    if (SKIPPED_DIRS.has(area) || !statSync(areaDir).isDirectory()) {
      continue
    }
    for (const path of listModules(areaDir)) {
      const modulePath = relative(srcDir, path)
        .split(sep)
        .join('/')
        .replace(/\.tsx?$/, '')
      const specifier = `${PACKAGE_NAME}/src/${modulePath}`
      const names = parseExports(path, readFileSync(path, 'utf8'))
      for (const { name } of names) {
        const owner = owners.get(name)
        if (owner) {
          throw new Error(
            `Duplicate export name ${name} in ${specifier} and ${owner}. Names are unique across the package.`,
          )
        }
        owners.set(name, specifier)
      }
      if (names.length > 0) {
        modules.push({ specifier, names })
      }
    }
  }

  return modules.sort((a, b) => a.specifier.localeCompare(b.specifier, 'en', { sensitivity: 'base' }))
}

function renderExport({ specifier, names }: ModuleExports): string {
  const parts = [...names]
    .sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }))
    .map(({ name, typeOnly }) => (typeOnly ? `type ${name}` : name))
  const oneLine = `export { ${parts.join(', ')} } from '${specifier}'`
  // Same wrapping as oxfmt: a single specifier stays on one line however long it is.
  if (parts.length === 1 || oneLine.length <= PRINT_WIDTH) {
    return oneLine
  }
  return `export {\n${parts.map((part) => `  ${part},`).join('\n')}\n} from '${specifier}'`
}

export function buildIndex(srcDir: string): string {
  return `${HEADER}\n${collectExports(srcDir).map(renderExport).join('\n')}\n`
}

/** Whitespace-insensitive so a formatter rewrap of a long export list never reads as drift. */
export function normalizeIndex(source: string): string {
  return source.replace(/,(\s*\})/g, '$1').replace(/\s+/g, '')
}

const scriptPath = fileURLToPath(import.meta.url)

if (process.argv[1] === scriptPath) {
  const srcDir = join(dirname(scriptPath), '..')
  const indexPath = join(srcDir, 'index.ts')
  const generated = buildIndex(srcDir)

  if (process.argv.includes('--check') || process.env['CI']) {
    if (normalizeIndex(generated) !== normalizeIndex(readFileSync(indexPath, 'utf8'))) {
      // oxlint-disable-next-line no-console -- CLI output
      console.error('src/index.ts is out of date. Run `bun transactions-ui generate:index`.')
      process.exit(1)
    }
  } else {
    writeFileSync(indexPath, generated)
  }
}
