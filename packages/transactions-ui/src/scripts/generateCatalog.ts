/**
 * Generates catalog.json: one entry per view component, so agents and engineers find the
 * view that exists before they write a new one.
 *
 *   bun transactions-ui generate:catalog           # write catalog.json
 *   bun transactions-ui generate:catalog --check   # exit 1 when catalog.json is stale
 *
 * Reads the same modules as the index generator: no tests, stories, platform legs or
 * `@internal` declarations. A component is an exported PascalCase function or const in a
 * .tsx module. Each entry carries its aliases (the `@alias` JSDoc tag: names someone would
 * search for instead), area, role (first sentence of its JSDoc), module, story title and
 * props (name, optional, first sentence of the prop's doc).
 *
 * Runs in Nx's `prepare` target next to the index generator, with the same split: it
 * writes locally and only checks when CI is set (here and in generateCatalog.test.ts).
 *
 * Deliberately dependency-free (regex and bracket counting, like generateIndex). It reads
 * the shapes the package's rules allow: props in an interface or object type, or inline.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { listModules, PACKAGE_NAME, SKIPPED_DIRS } from '@universe/transactions-ui/src/scripts/generateIndex'

const PACKAGE_DIR = 'packages/transactions-ui'
const PRINT_WIDTH = 120

const COMMENT =
  'Generated by src/scripts/generateCatalog.ts. Do not edit; run `bun transactions-ui generate:catalog`. ' +
  'Search names, aliases and roles here before writing a new transaction view.'

const COMPONENT_DECLARATION = /^export\s+(function|const)\s+([A-Z][A-Za-z0-9]*)\b/
const TYPE_DECLARATION =
  /^(?:export\s+)?(?:interface|type)\s+([A-Za-z_$][\w$]*)(?:<[^>]*>)?\s*(?:extends\s+([^{]+?))?\s*=?\s*\{/
const MEMBER = /^(?:readonly\s+)?([A-Za-z_$][\w$]*|'[^']*'|"[^"]*")(\?)?\s*(?::|\()/
const ALIAS_NAME = /^[A-Za-z][A-Za-z0-9]*$/
const ABBREVIATIONS = ['e.g.', 'i.e.', 'vs.']

export interface CatalogProp {
  name: string
  optional: boolean
  /** First sentence of the prop's doc comment. */
  doc: string | null
}

export interface CatalogEntry {
  name: string
  /** Other names for the same thing, from the `@alias` JSDoc tag. */
  aliases: string[]
  /** `common`, or the product folder (`swap`). */
  area: string
  /** First sentence of the component's JSDoc. */
  role: string | null
  module: string
  story: string | null
  /** The parameter's type as written, e.g. `DetailRowProps`. The module has the full types. */
  propsType: string | null
  props: CatalogProp[]
}

export interface Catalog {
  $comment: string
  import: string
  components: CatalogEntry[]
}

interface DocComment {
  description: string
  tags: Map<string, string[]>
}

interface TypeShape {
  body: string
  parents: string[]
}

interface ParsedModule {
  path: string
  area: string
  source: string
  lines: string[]
  types: Map<string, TypeShape>
}

function stripDocMarkers(line: string): string {
  return line
    .trim()
    .replace(/^\/\*\*\s?/, '')
    .replace(/\s?\*\/$/, '')
    .replace(/^\*\s?/, '')
}

function parseDoc(block: string[]): DocComment {
  const description: string[] = []
  const tags = new Map<string, string[]>()
  let tagValues: string[] | undefined
  for (const line of block.map(stripDocMarkers)) {
    const tag = /^@(\w+)\s*(.*)$/.exec(line.trim())
    if (tag?.[1]) {
      tagValues = tags.get(tag[1]) ?? []
      tagValues.push(tag[2] ?? '')
      tags.set(tag[1], tagValues)
    } else if (tagValues) {
      // Everything after the first tag belongs to a tag, never to the description.
      tagValues[tagValues.length - 1] = `${tagValues.at(-1) ?? ''} ${line.trim()}`.trim()
    } else {
      description.push(line)
    }
  }
  return { description: description.join('\n').trim(), tags }
}

/** The JSDoc block that ends right above `lineIndex`, looking past `//` lines. */
function docAbove(lines: string[], lineIndex: number): DocComment | undefined {
  let end = lineIndex - 1
  while (end >= 0 && (lines[end] ?? '').trim().startsWith('//')) {
    end--
  }
  if (end < 0 || !(lines[end] ?? '').trim().endsWith('*/')) {
    return undefined
  }
  let start = end
  while (start >= 0 && !(lines[start] ?? '').trim().startsWith('/**')) {
    start--
  }
  return start < 0 ? undefined : parseDoc(lines.slice(start, end + 1))
}

/** First sentence, on one line. Periods inside backticks and in `e.g.`, `i.e.`, `vs.` don't end it. */
export function firstSentence(text: string): string | null {
  const flat = text.replace(/\s+/g, ' ').trim()
  if (!flat) {
    return null
  }
  let inCode = false
  for (let i = 0; i < flat.length; i++) {
    const char = flat[i] ?? ''
    if (char === '`') {
      inCode = !inCode
    } else if (!inCode && '.!?'.includes(char) && (i === flat.length - 1 || flat[i + 1] === ' ')) {
      const sentence = flat.slice(0, i + 1)
      if (!ABBREVIATIONS.some((abbr) => sentence === abbr || sentence.endsWith(` ${abbr}`))) {
        return sentence
      }
    }
  }
  return flat
}

/** Text between the bracket at `openIndex` and its partner, skipping strings and comments. */
function balanced(source: string, openIndex: number): string | undefined {
  const pairs: Record<string, string> = { '{': '}', '(': ')', '[': ']' }
  const stack: string[] = []
  for (let i = openIndex; i < source.length; i++) {
    const char = source[i] ?? ''
    let skipTo: number | undefined
    if (char === '"' || char === "'" || char === '`') {
      skipTo = source.indexOf(char, i + 1)
    } else if (source.startsWith('//', i)) {
      skipTo = source.indexOf('\n', i)
    } else if (source.startsWith('/*', i)) {
      const close = source.indexOf('*/', i + 2)
      skipTo = close === -1 ? -1 : close + 1
    }
    if (skipTo !== undefined) {
      if (skipTo === -1) {
        return undefined
      }
      i = skipTo
      continue
    }
    const pair = pairs[char]
    if (pair) {
      stack.push(pair)
    } else if (char === stack.at(-1)) {
      stack.pop()
      if (stack.length === 0) {
        return source.slice(openIndex + 1, i)
      }
    }
  }
  return undefined
}

/** Splits `text` at `separator` wherever no bracket is open. */
function splitTopLevel(text: string, separator: string): string[] {
  const parts: string[] = []
  let depth = 0
  let last = 0
  for (let i = 0; i < text.length; i++) {
    const char = text[i] ?? ''
    if ('{(['.includes(char)) {
      depth++
    } else if ('})]'.includes(char)) {
      depth--
    } else if (depth === 0 && text.startsWith(separator, i)) {
      parts.push(text.slice(last, i))
      last = i + separator.length
    }
  }
  parts.push(text.slice(last))
  return parts
}

function bracketDelta(line: string): number {
  const code = line.replace(/(['"`])(?:\\.|(?!\1).)*\1/g, '').replace(/\/\/.*$/, '')
  return (code.match(/[{([]/g) ?? []).length - (code.match(/[})\]]/g) ?? []).length
}

/** Members of an interface or object type body, top level only. */
function parseMembers(body: string): CatalogProp[] {
  const props: CatalogProp[] = []
  let depth = 0
  let comment: string[] | undefined
  let pendingDoc: string | undefined
  for (const line of body.split('\n')) {
    const trimmed = line.trim()
    if (!comment && trimmed.startsWith('/*')) {
      comment = []
    }
    if (comment) {
      comment.push(line)
      if (trimmed.includes('*/')) {
        // Only a JSDoc block right above a top-level member documents it.
        pendingDoc = depth === 0 && comment[0]?.trim().startsWith('/**') ? parseDoc(comment).description : undefined
        comment = undefined
      }
      continue
    }
    if (depth === 0 && !trimmed.startsWith('//')) {
      // A one-line inline type (`{ a: string; b?: boolean }`) holds several members.
      for (const segment of splitTopLevel(trimmed, ';').flatMap((part) => splitTopLevel(part, ','))) {
        const member = MEMBER.exec(segment.trim())
        if (member?.[1]) {
          props.push({
            name: member[1].replace(/^['"]|['"]$/g, ''),
            optional: member[2] === '?',
            doc: pendingDoc ? firstSentence(pendingDoc) : null,
          })
          pendingDoc = undefined
        }
      }
    }
    if (!trimmed.startsWith('//')) {
      depth += bracketDelta(line)
    }
  }
  return props
}

function parseModule(path: string, area: string): ParsedModule {
  const source = readFileSync(path, 'utf8')
  const lines = source.split('\n')
  const types = new Map<string, TypeShape>()
  let offset = 0
  for (const line of lines) {
    const match = TYPE_DECLARATION.exec(line)
    const body = match?.[1] ? balanced(source, offset + line.lastIndexOf('{')) : undefined
    if (match?.[1] && body !== undefined) {
      types.set(match[1], { body, parents: match[2] ? splitTopLevel(match[2], ',').map((p) => p.trim()) : [] })
    }
    offset += line.length + 1
  }
  return { path, area, source, lines, types }
}

interface TypeLookup {
  local: Map<string, TypeShape>
  global: Map<string, TypeShape>
}

/** Props of a parameter type: a named interface or object type, an inline type, `&` or `PropsWithChildren`. */
function resolveProps(typeText: string, lookup: TypeLookup, seen: Set<string> = new Set()): CatalogProp[] {
  const text = typeText.trim()
  const intersection = splitTopLevel(text, '&')
  if (intersection.length > 1) {
    return intersection.flatMap((part) => resolveProps(part, lookup, seen))
  }
  if (text.startsWith('{')) {
    return parseMembers(text.slice(1, text.lastIndexOf('}')))
  }
  const withChildren = /^PropsWithChildren<([\s\S]*)>$/.exec(text)
  if (withChildren?.[1] !== undefined) {
    return [...resolveProps(withChildren[1], lookup, seen), { name: 'children', optional: true, doc: null }]
  }
  const shape = seen.has(text) ? undefined : (lookup.local.get(text) ?? lookup.global.get(text))
  if (!shape) {
    return []
  }
  seen.add(text)
  return [...shape.parents.flatMap((parent) => resolveProps(parent, lookup, seen)), ...parseMembers(shape.body)]
}

/** The type annotation on a function's first parameter, e.g. `DetailRowProps`. */
function parameterType(source: string, declarationOffset: number, name: string): string | null {
  const openIndex = source.indexOf('(', source.indexOf(name, declarationOffset))
  const params = openIndex === -1 ? undefined : balanced(source, openIndex)
  const [first = ''] = splitTopLevel(params ?? '', ',')
  const [, ...annotation] = splitTopLevel(first, ':')
  const [typeText = ''] = splitTopLevel(annotation.join(':'), ' = ')
  return typeText.trim() ? typeText.replace(/\s+/g, ' ').trim() : null
}

function parseAliases(doc: DocComment | undefined): string[] {
  return (doc?.tags.get('alias') ?? []).flatMap((value) => value.split(/[\s,]+/).filter(Boolean))
}

/**
 * The story that shows a component: the stories file whose meta `component` it is, else
 * its module's stories file when that renders it (GasSummary inside the GasRow stories).
 */
function storyFor(name: string, modulePath: string): string | null {
  const dir = dirname(modulePath)
  const moduleBase = basename(modulePath, '.tsx')
  let fallback: string | null = null
  for (const entry of readdirSync(dir).sort()) {
    if (!entry.endsWith('.stories.tsx')) {
      continue
    }
    const source = readFileSync(join(dir, entry), 'utf8')
    const title = /\btitle:\s*(['"])(.+?)\1/.exec(source)?.[2]
    if (!title) {
      continue
    }
    if (/\bcomponent:\s*([A-Z][\w$]*)/.exec(source)?.[1] === name) {
      return title
    }
    if (basename(entry, '.stories.tsx') === moduleBase && new RegExp(`\\b${name}\\b`).test(source)) {
      fallback = title
    }
  }
  return fallback
}

function componentsOf(module: ParsedModule, srcDir: string, global: Map<string, TypeShape>): CatalogEntry[] {
  const entries: CatalogEntry[] = []
  let offset = 0
  module.lines.forEach((line, index) => {
    const lineOffset = offset
    offset += line.length + 1
    const match = COMPONENT_DECLARATION.exec(line)
    const name = match?.[2]
    if (!name || !/[a-z]/.test(name)) {
      return
    }
    const doc = docAbove(module.lines, index)
    if (doc?.tags.has('internal')) {
      return
    }
    const propsType =
      match[1] === 'function'
        ? parameterType(module.source, lineOffset, name)
        : module.types.has(`${name}Props`)
          ? `${name}Props`
          : null
    entries.push({
      name,
      aliases: parseAliases(doc),
      area: module.area,
      role: doc ? firstSentence(doc.description) : null,
      module: `${PACKAGE_DIR}/src/${relative(srcDir, module.path).split(sep).join('/')}`,
      story: storyFor(name, module.path),
      propsType,
      props: propsType ? resolveProps(propsType, { local: module.types, global }) : [],
    })
  })
  return entries
}

/** One alias, one component, and never the name of another component: a search lands on one view. */
function assertAliases(components: CatalogEntry[]): void {
  const names = new Set(components.map((c) => c.name))
  const owners = new Map<string, string>()
  for (const { name, aliases } of components) {
    for (const alias of aliases) {
      if (!ALIAS_NAME.test(alias)) {
        throw new Error(`${name}: alias "${alias}" is not a PascalCase name.`)
      }
      if (names.has(alias)) {
        throw new Error(`${name}: alias ${alias} is already a component name. Aliases are names that don't exist here.`)
      }
      const owner = owners.get(alias)
      if (owner) {
        throw new Error(`Duplicate alias ${alias} on ${name} and ${owner}. One alias, one component.`)
      }
      owners.set(alias, name)
    }
  }
}

export function buildCatalog(srcDir: string): Catalog {
  const modules: ParsedModule[] = []
  for (const area of readdirSync(srcDir).sort()) {
    const areaDir = join(srcDir, area)
    if (!SKIPPED_DIRS.has(area) && statSync(areaDir).isDirectory()) {
      modules.push(...listModules(areaDir).map((path) => parseModule(path, area)))
    }
  }

  const global = new Map<string, TypeShape>()
  for (const module of modules) {
    for (const [name, shape] of module.types) {
      if (!global.has(name)) {
        global.set(name, shape)
      }
    }
  }

  const components = modules
    .filter((module) => module.path.endsWith('.tsx'))
    .flatMap((module) => componentsOf(module, srcDir, global))
  assertAliases(components)

  // common/ first: it is the shared answer. Then products, alphabetically.
  const areaKey = (area: string): string => (area === 'common' ? '' : area)
  components.sort(
    (a, b) =>
      areaKey(a.area).localeCompare(areaKey(b.area)) || a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }),
  )

  return { $comment: COMMENT, import: PACKAGE_NAME, components }
}

/** JSON in oxfmt's layout: objects expanded, arrays of plain values on one line when they fit. */
function printJson(value: unknown, indent: string, lineStart: number): string {
  const inner = `${indent}  `
  if (Array.isArray(value)) {
    const inline = `[${value.map((item) => JSON.stringify(item)).join(', ')}]`
    const plain = value.every((item) => item === null || typeof item !== 'object')
    // +1 for the comma after the value, which counts against the print width.
    if (value.length === 0 || (plain && lineStart + inline.length + 1 <= PRINT_WIDTH)) {
      return inline
    }
    return `[\n${value.map((item) => `${inner}${printJson(item, inner, inner.length)}`).join(',\n')}\n${indent}]`
  }
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value).map(([key, item]) => {
      const prefix = `${inner}${JSON.stringify(key)}: `
      return `${prefix}${printJson(item, inner, prefix.length)}`
    })
    return entries.length === 0 ? '{}' : `{\n${entries.join(',\n')}\n${indent}}`
  }
  return JSON.stringify(value)
}

export function renderCatalog(catalog: Catalog): string {
  return `${printJson(catalog, '', 0)}\n`
}

/** Compares parsed JSON, so a formatter rewrap never reads as drift. */
export function isCatalogCurrent(onDisk: string, catalog: Catalog): boolean {
  try {
    return JSON.stringify(JSON.parse(onDisk)) === JSON.stringify(catalog)
  } catch {
    return false
  }
}

const scriptPath = fileURLToPath(import.meta.url)

if (process.argv[1] === scriptPath) {
  const srcDir = join(dirname(scriptPath), '..')
  const catalogPath = join(srcDir, '..', 'catalog.json')
  const catalog = buildCatalog(srcDir)

  if (process.argv.includes('--check') || process.env['CI']) {
    let onDisk = ''
    try {
      onDisk = readFileSync(catalogPath, 'utf8')
    } catch {
      // Missing file: reported as stale below.
    }
    if (!isCatalogCurrent(onDisk, catalog)) {
      // oxlint-disable-next-line no-console -- CLI output
      console.error('catalog.json is out of date. Run `bun transactions-ui generate:catalog`.')
      process.exit(1)
    }
  } else {
    writeFileSync(catalogPath, renderCatalog(catalog))
  }
}
