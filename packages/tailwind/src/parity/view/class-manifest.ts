/**
 * The Tailwind utility-candidate manifest for the workbench View parity page.
 *
 * `ViewCompat` computes its className at runtime, so Tailwind's static
 * scanner never sees the candidates in source. The parity matrix is finite
 * and deterministic, so the exact utility set is enumerated here and checked
 * into the workbench as `view-parity.classes.txt` (referenced from `app.css`
 * via `@source`).
 *
 * The workbench `generate:option-classes` script writes the file; the
 * regenerate-and-diff test in `class-manifest.test.ts` fails whenever the
 * checked-in manifest drifts from this enumeration.
 */
// Relative cross-package import: a package dep edge tailwind → mycelium would cycle (mycelium already depends on tailwind).
// nx-ignore-next-line
import { viewCompatClassName } from '../../../../mycelium/src/view-compat/compile'
import { buildMatrix } from './matrix'

/** Sorted, de-duplicated utility candidates for the whole parity matrix. */
export function buildViewParityClassManifest(): string[] {
  const classes = new Set<string>()
  for (const { props } of buildMatrix()) {
    for (const candidate of viewCompatClassName(props).split(' ')) {
      if (candidate !== '') {
        classes.add(candidate)
      }
    }
  }
  return [...classes].sort()
}

/** The exact `view-parity.classes.txt` file contents. */
export function viewParityManifestFileContents(): string {
  const lines = [
    '# Generated by `bun run generate:option-classes` — do not edit.',
    '# Tailwind utility candidates for every parity-matrix case rendered by the View parity page.',
    ...buildViewParityClassManifest(),
  ]
  return `${lines.join('\n')}\n`
}
