// nx-ignore-next-line
import { parseGroupStateProp } from '../../../../mycelium/src/compat/group'
/**
 * The Tailwind utility-candidate manifest for the workbench Flex parity page.
 *
 * `FlexCompat` computes its className at runtime, so Tailwind's static scanner
 * never sees the candidates in source. The parity matrix is finite and
 * deterministic, so the exact utility set is enumerated here — every case the
 * board renders, its forced pseudo-state pairs, and the group containers
 * `$group-*` cases are wrapped in — and checked into the workbench as
 * `flex-parity.classes.txt` (referenced from `app.css` via `@source`).
 *
 * The workbench `generate:flex-parity-classes` script writes the file; the
 * regenerate-and-diff test in `class-manifest.test.ts` fails whenever the
 * checked-in manifest drifts from this enumeration.
 */
// Relative cross-package import: a package dep edge tailwind → mycelium would cycle (mycelium already depends on tailwind).
// nx-ignore-next-line
import { flexCompatClassName, type FlexCompatProps } from '../../../../mycelium/src/flex-compat/compile'
import { buildMatrix } from './matrix'

const PSEUDO_FORCE_STYLES = {
  hoverStyle: 'hover',
  pressStyle: 'press',
  focusStyle: 'focus',
  focusVisibleStyle: 'focusVisible',
  focusWithinStyle: 'focusWithin',
} as const

/** The group container a `$group-*` case renders inside, via the shared group parser. */
function groupContainerName(props: FlexCompatProps): string | boolean | undefined {
  for (const key of Object.keys(props)) {
    const parts = parseGroupStateProp(key)
    if (parts !== undefined) {
      return parts.name ?? true
    }
  }
  return undefined
}

/**
 * Everything the board renders for one matrix case: the case itself, a
 * forced-state pair per pseudo pool, and the group container wrapper. The
 * board's disabled pairs add no candidates — `disabled` only sets the
 * `aria-disabled` attribute, the classes are unchanged.
 */
function renderedPropVariants(props: FlexCompatProps): FlexCompatProps[] {
  const variants: FlexCompatProps[] = [props]
  for (const [pseudoKey, forceStyle] of Object.entries(PSEUDO_FORCE_STYLES)) {
    if (props[pseudoKey as keyof typeof PSEUDO_FORCE_STYLES] !== undefined) {
      variants.push({ ...props, forceStyle })
    }
  }
  const group = groupContainerName(props)
  if (group !== undefined) {
    variants.push({ group, fill: true })
  }
  return variants
}

/** Sorted, de-duplicated utility candidates for the whole parity board. */
export function buildFlexParityClassManifest(): string[] {
  const classes = new Set<string>()
  for (const { props } of buildMatrix()) {
    for (const variant of renderedPropVariants(props)) {
      for (const candidate of flexCompatClassName(variant).split(' ')) {
        if (candidate !== '') {
          classes.add(candidate)
        }
      }
    }
  }
  return [...classes].sort()
}

/** The exact `flex-parity.classes.txt` file contents. */
export function flexParityManifestFileContents(): string {
  const lines = [
    '# Generated by `bun run generate:option-classes` — do not edit.',
    '# What this is: the Tailwind `@source` manifest for the Flex (Spore) parity page.',
    '# FlexCompat computes its className at runtime from props, so the Tailwind scanner',
    '# never sees these candidates in source files; this enumeration (every parity-matrix case the',
    '# verification board renders, produced through the real compiler) is how their CSS gets emitted.',
    '# Guarded by packages/tailwind/src/parity/flex/class-manifest.test.ts (regenerate-and-diff).',
    ...buildFlexParityClassManifest(),
  ]
  return `${lines.join('\n')}\n`
}
