import { HookDetailsDescription } from '~/pages/HookDetails/components/HookDetailsDescription'
import { render, screen } from '~/test-utils/render'

describe('HookDetailsDescription', () => {
  it('attributes a description to AI only with an explicit origin', () => {
    const { rerender } = render(
      <HookDetailsDescription description="Adjusts swap fees." descriptionGeneratedByAi={false} />,
    )
    expect(screen.getByText('Adjusts swap fees.')).toBeInTheDocument()
    expect(screen.queryByText('Description generated by AI')).not.toBeInTheDocument()

    rerender(<HookDetailsDescription description="Adjusts swap fees." descriptionGeneratedByAi />)
    expect(screen.getByText('Description generated by AI')).toBeInTheDocument()
  })

  it('shows the missing-description fallback without an AI attribution', () => {
    render(<HookDetailsDescription description="   " descriptionGeneratedByAi />)

    expect(screen.getByText('No description available.')).toBeInTheDocument()
    expect(screen.queryByText('Description generated by AI')).not.toBeInTheDocument()
  })
})
